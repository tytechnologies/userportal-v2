-- =====================================================================
-- 1. tasks — additive columns
-- =====================================================================

ALTER TABLE public.tasks
  ADD COLUMN IF NOT EXISTS deal_id uuid REFERENCES public.deals(id) ON DELETE CASCADE,
  ADD COLUMN IF NOT EXISTS auto_generated boolean NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS last_reminder_sent_at timestamptz;

-- Hot indexes for the workflow inbox + reminder cron:
CREATE INDEX IF NOT EXISTS tasks_deal_idx
  ON public.tasks(deal_id) WHERE deal_id IS NOT NULL;
-- "due in next 24h, not yet reminded" — the reminder cron's only
-- query. Partial index keeps the working set tiny.
CREATE INDEX IF NOT EXISTS tasks_due_reminder_idx
  ON public.tasks(due_at)
  WHERE due_at IS NOT NULL
    AND completed_at IS NULL
    AND last_reminder_sent_at IS NULL;
-- "open tasks for assignee" — dashboard widget query.
CREATE INDEX IF NOT EXISTS tasks_assignee_open_idx
  ON public.tasks(assigned_to_user_id, due_at)
  WHERE completed_at IS NULL;

COMMENT ON COLUMN public.tasks.deal_id IS
  'Optional FK to deals. When set, the task is part of a deal workflow (auto-generated by stage transitions or manually attached). RLS inherits via deal participation when set.';
COMMENT ON COLUMN public.tasks.auto_generated IS
  'true when the task was created by automation_task_templates trigger. UI surfaces this so operators see "auto-created when deal moved to documentation" rather than mystery tasks.';


-- =====================================================================
-- 2. automation_task_templates — seeded rule registry
-- =====================================================================
--
-- Each row defines one rule: "when <trigger_event> matches
-- <trigger_match>, create a task with <task_template>".
--
-- Trigger events supported (free-form text — operators can extend):
--   deal.stage_changed  trigger_match: { to_stage: '<stage_key>' }
--
-- task_template jsonb:
--   { title: string, description?: string, due_offset_hours: int,
--     priority?: string }
--
-- One rule can spawn one task per deal stage transition. To spawn
-- multiple (e.g., a documentation checklist), seed multiple rules
-- with the same trigger_match.

CREATE TABLE IF NOT EXISTS public.automation_task_templates (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  trigger_event   text NOT NULL CHECK (trigger_event IN (
                       'deal.stage_changed'
                     )),
  trigger_match   jsonb NOT NULL DEFAULT '{}'::jsonb,
  task_template   jsonb NOT NULL,
  enabled         boolean NOT NULL DEFAULT true,
  description     text,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS automation_task_templates_trigger_idx
  ON public.automation_task_templates(trigger_event)
  WHERE enabled = true;

DROP TRIGGER IF EXISTS set_automation_task_templates_updated_at
  ON public.automation_task_templates;
CREATE TRIGGER set_automation_task_templates_updated_at
  BEFORE UPDATE ON public.automation_task_templates
  FOR EACH ROW EXECUTE FUNCTION public.set_current_timestamp_updated_at();

ALTER TABLE public.automation_task_templates ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS automation_task_templates_select ON public.automation_task_templates;
CREATE POLICY automation_task_templates_select
  ON public.automation_task_templates FOR SELECT
  TO authenticated USING (true);
-- INSERT/UPDATE/DELETE: service-role only. Operators add rules via
-- SQL until a config UI ships.

COMMENT ON TABLE public.automation_task_templates IS
  'Seeded rule registry for deterministic task auto-generation. trigger_event + trigger_match define when; task_template defines what. Service-role-only writes (no DSL UI v1).';

