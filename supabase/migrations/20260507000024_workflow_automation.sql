-- Workflow Automation + Smart Operations.
--
-- Lightweight, deterministic automation layer. NO DSL, NO AI:
-- the rules are seeded SQL templates that fire on deal stage
-- transitions; SLA breaches and recommendations are derived views.
--
-- Three additive objects:
--   1. public.tasks gets `deal_id`, `auto_generated`,
--      `last_reminder_sent_at` columns (additive only)
--   2. public.automation_task_templates — seeded rule registry
--   3. public.pipeline_alerts (view) — SLA / stale-state alerts
--   4. public.pipeline_recommendations (view) — next-action hints
--
-- Plus: trigger on deals UPDATE that materializes templates into
-- tasks rows; daily reminder cron that fires notifications for
-- approaching due dates.
--
-- ROLLBACK:
--   SELECT cron.unschedule('tasks_reminder_daily');
--   DROP VIEW IF EXISTS public.pipeline_recommendations;
